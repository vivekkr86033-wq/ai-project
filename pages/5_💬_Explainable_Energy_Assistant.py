"""
5_💬_Explainable_Energy_Assistant.py — Explainable Generative Assistant.

Translates complex optimization schedules, symbolic rule activations, and multi-agent
telemetry into plain-English, actionable explanations for homeowners.
"""

import streamlit as st
from src.energy_models import get_default_appliances, get_simulation_profile
from src.appliance_search import run_astar_search, run_baseline_asap
from src.rule_engine import EnergyRuleEngine
from src.energy_assistant import generate_energy_explanation
from src.config import (
    llm_available,
    get_llm_provider,
    get_openai_model,
    get_gemini_model,
    get_active_model,
    check_gemini_connection,
)


def render():
    st.markdown("## 💬 Explainable Generative Energy Assistant")
    st.markdown(
        "Ask natural-language questions about automated energy decisions, tariff impacts, battery operations, "
        "and daily savings. Responses are strictly grounded in real-time telemetry, A* optimization paths, and symbolic rule traces."
    )

    # Initialize chat history and live API status
    if "energy_chat_history" not in st.session_state:
        st.session_state.energy_chat_history = []
    if "gemini_live_success" not in st.session_state:
        st.session_state.gemini_live_success = False
    if "gemini_last_error" not in st.session_state:
        st.session_state.gemini_last_error = None
    if "dev_mode" not in st.session_state:
        st.session_state.dev_mode = False

    # Mode Selector Header
    top_col1, top_col2 = st.columns([2.5, 1.5])

    with top_col2:
        c_mode, c_dev = st.columns(2)
        with c_mode:
            force_fallback = st.toggle(
                "Deterministic Fallback",
                value=False,
                help="When ON, answers are generated by a deterministic offline synthesis engine (zero API cost, 100% faithful to telemetry). When OFF, uses Gemini API if available.",
            )
        with c_dev:
            dev_mode = st.toggle(
                "🛠️ Dev Mode",
                value=st.session_state.dev_mode,
                help="Show detailed API diagnostics, exact model verification, and sanitized error reasons.",
            )
            st.session_state.dev_mode = dev_mode

        if dev_mode and not force_fallback:
            if st.button("⚡ Test Gemini API", use_container_width=True):
                with st.spinner("Pinging Google Gemini API..."):
                    ok, msg = check_gemini_connection()
                    st.session_state.gemini_live_success = ok
                    if ok:
                        st.session_state.gemini_last_error = None
                        st.toast("✅ Gemini API connected successfully!")
                    else:
                        st.session_state.gemini_last_error = msg
                        st.toast("⚠️ Gemini API returned an error.")
                st.rerun()

    with top_col1:
        provider = get_llm_provider()
        active_model = get_gemini_model()

        # Display "Gemini AI Active" when Gemini is configured and available
        if not force_fallback and provider == "gemini" and llm_available():
            st.success(f"🤖 Powered by **Gemini AI Active** (`{active_model}`) with Telemetry Grounding")
        elif not force_fallback and provider == "openai" and llm_available():
            st.success(f"🤖 Powered by **OpenAI Active** (`{get_openai_model()}`) with Telemetry Grounding")
        else:
            st.info("⚡ Powered by **Deterministic Fallback Engine** (Offline, zero hallucinations)")
            if dev_mode and st.session_state.get("gemini_last_error"):
                st.warning(
                    f"**API Diagnostic Notice (Dev Mode):**\n\n"
                    f"`{st.session_state.get('gemini_last_error')}`"
                )

    # Prepare simulation data for grounding context
    telemetry = get_simulation_profile("summer_peak")
    appliances = get_default_appliances()
    astar_res = run_astar_search(appliances, telemetry, max_grid_kw=10.0)
    baseline_res = run_baseline_asap(appliances, telemetry)

    engine = EnergyRuleEngine()
    rule_traces = [engine.evaluate_hour(t, appliances=appliances) for t in telemetry]

    # ── Quick-Prompt Suggestion Pills ──────────────────────────
    st.markdown("##### 💡 Suggested Questions")
    pills = [
        "Why was my EV charging delayed to 2:00 AM?",
        "How much money did the A* optimizer and battery save me today?",
        "What rules fired to protect my battery reserve?",
        "What happens if grid prices spike at 6:00 PM?",
    ]

    pill_cols = st.columns(4)
    selected_prompt = None

    for idx, prompt in enumerate(pills):
        with pill_cols[idx]:
            if st.button(prompt, use_container_width=True, key=f"pill_{idx}"):
                selected_prompt = prompt

    # ── Display Conversation History ───────────────────────────
    for msg in st.session_state.energy_chat_history:
        with st.chat_message(msg["role"], avatar="⚡" if msg["role"] == "assistant" else "👤"):
            st.markdown(msg["content"])
            if msg.get("citations"):
                with st.expander("📚 Grounded Citations & Verified Sources", expanded=False):
                    for cite in msg["citations"]:
                        st.markdown(f"- 📄 `{cite}`")
                    mode_label = (
                        "Gemini AI Active"
                        if msg.get("mode") == "llm" and msg.get("provider") == "gemini"
                        else ("OpenAI Active" if msg.get("mode") == "llm" else "Deterministic Fallback")
                    )
                    st.caption(f"Status: **{mode_label}** | Model: `{msg.get('model', 'none')}`")

            if dev_mode and msg.get("error"):
                with st.expander("🛠️ API Error Diagnostic (Dev Mode)", expanded=False):
                    st.code(msg["error"], language="text")

    # ── Handle Input ──────────────────────────────────────────
    user_input = st.chat_input("Ask a question about your home energy management…") or selected_prompt

    if user_input:
        # Append user message
        st.session_state.energy_chat_history.append({"role": "user", "content": user_input})
        with st.chat_message("user", avatar="👤"):
            st.markdown(user_input)

        # Generate grounded explanation
        with st.chat_message("assistant", avatar="⚡"):
            with st.spinner("Analyzing telemetry & generating explainable reasoning…"):
                res = generate_energy_explanation(
                    user_query=user_input,
                    search_result=astar_res,
                    baseline_result=baseline_res,
                    rule_traces=rule_traces,
                    telemetry_profile=telemetry,
                    force_fallback=force_fallback,
                )

            # Update live success status based on actual execution path
            if res.get("mode") == "llm" and res.get("provider") == "gemini":
                st.session_state.gemini_live_success = True
                st.session_state.gemini_last_error = None
            else:
                st.session_state.gemini_live_success = False
                if res.get("error"):
                    st.session_state.gemini_last_error = res.get("error")

            st.markdown(res["answer"])

            if res.get("citations"):
                with st.expander("📚 Grounded Citations & Verified Sources", expanded=False):
                    for cite in res["citations"]:
                        st.markdown(f"- 📄 `{cite}`")
                    res_mode_label = (
                        "Gemini AI Active"
                        if res.get("mode") == "llm" and res.get("provider") == "gemini"
                        else ("OpenAI Active" if res.get("mode") == "llm" else "Deterministic Fallback")
                    )
                    st.caption(f"Status: **{res_mode_label}** | Model: `{res.get('model')}`")

            if dev_mode and res.get("error"):
                with st.expander("🛠️ API Error Diagnostic (Dev Mode)", expanded=False):
                    st.code(res["error"], language="text")

        # Save assistant message
        st.session_state.energy_chat_history.append({
            "role": "assistant",
            "content": res["answer"],
            "citations": res.get("citations", []),
            "mode": res.get("mode"),
            "provider": res.get("provider"),
            "model": res.get("model"),
            "error": res.get("error"),
        })


render()
